'use strict';

// G7 inventory and generator smoke contracts. Do not interpret these as
// family-specific assessment, mathematical or classroom acceptance tests.
const fs=require('fs');
const M=require('../../assets/99club/goodies-angles.js');
const library=require('../../assets/99club/geometry-construction-methods.json');
const path='docs/99club-geometry-family-coverage.md';
const assert=(ok,message)=>{if(!ok)throw new Error(message)};
const ids=M.FAMILIES.map(f=>f[0]),primary=M.types({}).map(t=>t.id);
const all=M.types({enrichment:true}).map(t=>t.id),groups=M.challengeGroups({enrichment:true});
const methods=new Set(library.methods.map(m=>m.id)),mapped=M.CONSTRUCTION_METHODS_BY_TASK;
assert(new Set(ids).size===ids.length,'Duplicate geometry family ID');
assert(all.length===ids.length&&ids.every(id=>all.includes(id)),'Opt-in catalogue loses a family');
assert(primary.length===M.FAMILIES.filter(f=>f[3]!==7).length,'Default catalogue count');
assert(M.FAMILIES.every(([id,,,year])=>primary.includes(id)===(year!==7)),'Primary/enrichment leakage');
assert(new Set(library.methods.map(m=>m.id)).size===library.methods.length,'Duplicate method ID');
assert(Object.keys(mapped).length===M.labTypes.length&&M.labTypes.every(id=>methods.has(mapped[id])),'Missing assessed construction mapping');
assert(methods.size===new Set(Object.values(mapped)).size&&[...methods].every(id=>Object.values(mapped).includes(id)),'Unmapped illustrated method');
for(const m of library.methods)assert(m.steps.length===m.graphics.frames.length,'Guide stage mismatch: '+m.id);
let seed=12345;
const rng=()=>((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/4294967296);
const counts={generated:0,choice:0,multipart:0,construction:0,response:0};
const rows=[];
for(const [id,label,mode,year] of M.FAMILIES){
 const memberships=groups.filter(g=>g.ids.includes(id));
 assert(memberships.length===1,'Family must occur in exactly one launcher group: '+id);
 const routes=new Set();
 for(const [level] of M.LEVELS)for(let j=0;j<24;j++){
  const t=M.generate({type:id,mode,level,enrichment:year===7},rng);
  counts.generated++;
  assert(t.type===id&&t.mode===mode&&typeof t.prompt==='string'&&t.prompt.length&&typeof t.answer==='string'&&t.answer.length&&typeof t.note==='string'&&t.note.length,'Missing task/answer/marking data: '+id+' '+level);
  let route;
  if(t.choices){route='Choice';counts.choice++;assert(t.choices.includes(t.answer),'Expected answer missing from choices: '+id)}
  else if(t.parts){route='Multi-part';counts.multipart++;assert(t.parts.length>=2&&t.parts.every(p=>Number.isFinite(p.answer)&&p.label&&p.unit),'Invalid subparts: '+id)}
  else if(M.labTypes.includes(id)||['draw','draw-reflex'].includes(id)){route='Drawing / construction';counts.construction++}
  else{route='Response';counts.response++}
  routes.add(route);
 }
 rows.push('| `'+id+'` | '+label.replace(/\|/g,'\\|')+' | '+(year===7?'KS3 opt-in':'Y'+year)+' | '+mode+' | '+memberships[0].id+' | '+[...routes].join(' / ')+' | '+(mapped[id]?'`'+mapped[id]+'`':'—')+' | 72/72 |');
}
const matrix=[
'# Geometry challenge family coverage — G7 working inventory',
'',
'Generated by `node scripts/99club/goodies-geometry-coverage-qa.js --write`. The default invocation checks the inventory against current code and fails on drift. Year labels are advisory teaching defaults, not a statutory curriculum certification.',
'',
'## Verified inventory and scope',
'',
'- '+ids.length+' native challenge families: '+primary.length+' primary/default and '+(ids.length-primary.length)+' opt-in enrichment. '+groups.length+' non-overlapping launcher groups.',
'- '+M.labTypes.length+' assessed construction task IDs mapped to '+methods.size+' illustrated guides. A shared guide may support two assessed outcomes.',
'- '+counts.generated.toLocaleString('en-GB')+' seeded task generation samples: 24 per difficulty, three difficulties, per family. Prompt, answer, marking note, type, mode, choice answer membership and finite multi-part answers checked.',
'- The assessment column identifies the response route inferred from actual generated records; it does **not** certify that every correct or incorrect response is assessed correctly.',
'- Current capture, batch and mixed publication use the shared Angles & geometry adapter. Every family still needs specific pupil/teacher rendering, answer leakage, alternative solution, save/reopen, and touch evidence recorded before sign-off. The generator test is not that evidence.',
'- This inventory covers the Angles & geometry widget only. Coordinate Grid, Geoboard, Measures and other geometry-related widgets need their own crosswalk. The absence of a standalone family here does not establish a whole-Studio curriculum gap.',
'',
'## Family-level inventory',
'',
'| Stable family ID | Challenge | Advisory stage | Mode | Launcher group ID | Assessment route | Illustrated method ID | Generation samples |',
'|---|---|---|---|---|---|---|---|',
...rows,
'',
'## Acceptance work remaining',
'',
'Use this exact inventory to record family-specific evidence for mathematical invariants, valid/invalid assessment, saved state, current/batch/mixed publishing, pupil and teacher output, graphical annex, touch and physical A4. Separate curriculum objective mapping (statutory/guidance/enrichment) from advisory year labels. Do not mark a family complete on the basis of this smoke test. For construction, record whether tool permissions and method evidence are verified separately from final geometry. For multi-part questions, record independent subpart marking and any teacher-only method credit.',
''
].join('\n');
if(process.argv.includes('--write'))fs.writeFileSync(path,matrix);
else assert(fs.readFileSync(path,'utf8')===matrix,'Geometry coverage matrix is stale; regenerate with --write and review changes');
console.log('Geometry family inventory: '+ids.length+' families, '+counts.generated+' generation records, '+M.labTypes.length+' assessed construction IDs, '+methods.size+' methods. No inventory drift.');
